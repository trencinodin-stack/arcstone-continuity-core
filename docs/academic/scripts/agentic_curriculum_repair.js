const fs = require('fs');
const path = require('path');

function parseArgs() {
  const args = process.argv.slice(2);
  const options = {
    schema: 'docs/academic/schema/dae_pedagogy_v1.json',
    errorLog: 'harness_audit.log',
    outDir: 'docs/academic/harness',
  };

  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--schema' && args[i + 1]) options.schema = args[++i];
    if (args[i] === '--error-log' && args[i + 1]) options.errorLog = args[++i];
    if (args[i] === '--out-dir' && args[i + 1]) options.outDir = args[++i];
  }
  return options;
}

